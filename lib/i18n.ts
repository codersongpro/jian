const symMath = (id: string, k: number) => {
  if (id === "i")
    return `i${["⁰", "¹", "²", "³"][k % 4]} = ${["1", "i", "−1", "−i"][k % 4]}`;
  if (id === "sqrt") {
    const n = (k % 5) + 1;
    return `√${n * n} = ${n}`;
  }
  if (id === "sigma") {
    const n = (k % 7) + 1;
    return `${Array.from({ length: n }, (_, i) => i + 1).join(" + ")} = ${(n * (n + 1)) / 2}`;
  }
  if (id === "e") {
    const n = 2 ** (k % 12);
    return `(1 + 1/${n})^${n} = ${((1 + 1 / n) ** n).toFixed(5)}`;
  }
  return "";
};
